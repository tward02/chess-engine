package com.tward.engine.tournament

import com.tward.engine.board.Board
import com.tward.engine.board.Colour
import com.tward.engine.board.Move
import com.tward.engine.game.ChessGame
import com.tward.engine.openingBook.OpeningBook
import com.tward.engine.player.bot.EliteNegamaxBot
import com.tward.engine.player.evaluator.CompactEvaluator
import java.nio.file.Files
import java.nio.file.Paths
import kotlin.math.abs
import kotlin.random.Random

/**
 * A fixed set of balanced start positions (one full FEN per line, `#` comments allowed). Testing
 * harnesses play each position twice with colours swapped, so the result measures the bots, not
 * which side the opening favoured.
 */
object OpeningSuite {
    const val DEFAULT_RESOURCE = "/openings/balanced.epd"

    fun load(resource: String = DEFAULT_RESOURCE): List<String> {
        val text = OpeningSuite::class.java.getResource(resource)?.readText()
            ?: error("opening suite $resource not found on the classpath")
        return parse(text)
    }

    fun parse(text: String): List<String> = text.lineSequence()
        .map(String::trim)
        .filter { it.isNotEmpty() && !it.startsWith("#") }
        .toList()
}

// Fixed-depth handcrafted search that exposes its root score.
private class JudgeBot(depth: Int) : EliteNegamaxBot(
    colour = Colour.WHITE, fixedDepth = depth, useOpeningBookMoves = false,
    evaluator = CompactEvaluator(), transpositionTableBits = 18
) {
    var lastScore = 0

    override fun searchRoot(
        game: ChessGame, depth: Int, previousBest: Move?, alpha: Int, beta: Int
    ): Pair<Move, Int> = super.searchRoot(game, depth, previousBest, alpha, beta)
        .also { lastScore = it.second }
}

private const val MIN_PLIES = 6
private const val PLY_RANGE = 7          // 6..12
private const val MAX_IMBALANCE = 50     // cp, side-to-move perspective
private const val MAX_ATTEMPTS = 50_000

/**
 * Builds an [OpeningSuite]: walks the main opening book with its weighted-random choice for a
 * random 6–12 plies, then keeps positions a fixed-depth handcrafted search scores within
 * [MAX_IMBALANCE] cp. The judge deliberately uses [CompactEvaluator], not a net, so the suite
 * cannot favour either side of an NNUE comparison.
 *
 * Run via `:engine:generateOpeningSuite`, `-PnnueArgs="count=500 depth=6 seed=1 weight=0.3 out=..."`.
 * `weight` flattens the book's play counts (count^weight): 1 follows the main lines, which repeat
 * far too often to fill a suite; 0 picks every book move equally.
 */
fun main(args: Array<String>) {
    val opts = args.associate { it.substringBefore('=') to it.substringAfter('=') }
    val count = opts["count"]?.toInt() ?: 500
    val depth = opts["depth"]?.toInt() ?: 6
    val random = Random(opts["seed"]?.toLong() ?: 1L)
    val out = Paths.get(opts["out"] ?: "src/test/resources/openings/balanced.epd")
    val weight = opts["weight"]?.toDouble() ?: 0.3

    val book = OpeningBook("/moveBook/Book.txt")
    val suite = LinkedHashSet<String>()
    var attempts = 0
    var shortLines = 0
    var duplicates = 0
    var unbalanced = 0

    while (suite.size < count && attempts < MAX_ATTEMPTS) {
        attempts++
        val game = ChessGame(Board.getStartingBoard())
        val targetPlies = MIN_PLIES + random.nextInt(PLY_RANGE)
        var plies = 0
        while (plies < targetPlies) {
            val entries = book.movesFor(game.board.toFEN(isFullFEN = false)) ?: break
            // Weighted by flattened play count, seeded for reproducibility.
            val weights = entries.map { Math.pow(it.numTimesPlayed.toDouble(), weight) }
            var pick = random.nextDouble() * weights.sum()
            val chosen = entries[weights.indices.firstOrNull { pick -= weights[it]; pick < 0 } ?: entries.lastIndex]
            val move = game.getLegalMoves().firstOrNull { it.toAlgebraic() == chosen.moveStr } ?: break
            game.makeMove(move)
            plies++
        }
        if (plies < MIN_PLIES || game.getGameResult() != null) {
            shortLines++
            continue
        }

        val fen = game.board.toFEN()
        if (fen in suite) {
            duplicates++
            continue
        }

        val judge = JudgeBot(depth)
        judge.chooseMove(game, 0)
        if (abs(judge.lastScore) <= MAX_IMBALANCE) {
            suite += fen
            if (suite.size % 50 == 0) println("  ${suite.size}/$count positions ($attempts tried)")
        } else {
            unbalanced++
        }
    }

    Files.createDirectories(out.toAbsolutePath().parent)
    Files.write(
        out,
        listOf(
            "# Balanced opening suite: $MIN_PLIES-${MIN_PLIES + PLY_RANGE - 1} book plies (weight $weight), " +
                    "|score| <= $MAX_IMBALANCE cp at depth $depth (CompactEvaluator). Generated by OpeningSuite.kt."
        ) + suite
    )
    println(
        "Wrote ${suite.size} positions to ${out.toAbsolutePath()} ($attempts tried: " +
                "$shortLines left the book early, $duplicates duplicates, $unbalanced unbalanced)"
    )
}
